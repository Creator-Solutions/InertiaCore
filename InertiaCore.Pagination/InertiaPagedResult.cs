using System.Collections.Generic;

namespace InertiaCore.Pagination
{
    /// <summary>
    /// Result of an Inertia-style paginated request. Contains the page of data and
    /// metadata/links needed for Next/Prev/First/Last page navigation.
    /// </summary>
    /// <typeparam name="T">The element type of the data list.</typeparam>
    public sealed record InertiaPagedResult<T>
    {
        /// <summary>
        /// The items for the current page.
        /// </summary>
        public IReadOnlyList<T> Data { get; init; } = [];

        /// <summary>
        /// Links for navigating between pages (First, Last, Previous, Next). Any of these
        /// may be <see langword="null"/> if the corresponding page does not exist.
        /// </summary>
        public InertiaPaginationLinks Links { get; init; } = new();

        /// <summary>
        /// Pagination metadata.
        /// </summary>
        public InertiaPaginationMeta Meta { get; init; } = new();
    }

    /// <summary>
    /// Navigation links generated by <see cref="InertiaPagedResult{T}"/>.
    /// </summary>
    public sealed record InertiaPaginationLinks
    {
        /// <summary>
        /// Link to the first page. <see langword="null"/> if the result set is empty.
        /// </summary>
        public string? First { get; init; }

        /// <summary>
        /// Link to the last page. <see langword="null"/> if the result set is empty.
        /// </summary>
        public string? Last { get; init; }

        /// <summary>
        /// Link to the previous page. <see langword="null"/> if on the first page.
        /// </summary>
        public string? Prev { get; init; }

        /// <summary>
        /// Link to the next page. <see langword="null"/> if on the last page.
        /// </summary>
        public string? Next { get; init; }
    }

    /// <summary>
    /// Metadata about the paginated result: current and last page numbers,
    /// items per page, total item count and the inclusive range of displayed items.
    /// </summary>
    public sealed record InertiaPaginationMeta
    {
        /// <summary>
        /// Current page number (1‑based).
        /// </summary>
        public int CurrentPage { get; init; }

        /// <summary>
        /// Total number of pages in the result set.
        /// </summary>
        public int LastPage { get; init; }

        /// <summary>
        /// Items per page.
        /// </summary>
        public int PerPage { get; init; }

        /// <summary>
        /// Total number of items in the result set.
        /// </summary>
        public int Total { get; init; }

        /// <summary>
        /// First item displayed on the current page (1‑based). <c>null</c> when the result set is empty.
        /// </summary>
        public int? From { get; init; }

        /// <summary>
        /// Last item displayed on the current page (1‑based). <c>null</c> when the result set is empty.
        /// </summary>
        public int? To { get; init; }

        /// <summary>
        /// Absolute path of the pagination endpoint.
        /// </summary>
        public string Path { get; init; } = null!;
    }
}
